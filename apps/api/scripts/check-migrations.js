// Fails if a migration drops a pgvector HNSW index.
//
// The HNSW indexes on resume_embeddings / job_embeddings are created with raw SQL because Prisma
// cannot model an index on an Unsupported("vector") column. As a result `prisma migrate dev`
// proposes DROP INDEX for them every time it generates a migration. Remove those statements by hand.
const fs = require('fs');
const path = require('path');

const dir = path.join(__dirname, '..', 'prisma', 'migrations');
const dropsHnsw = /DROP\s+INDEX\s+(IF\s+EXISTS\s+)?"?[\w.]*hnsw[\w]*"?/i;

const offenders = fs
  .readdirSync(dir, { withFileTypes: true })
  .filter((d) => d.isDirectory())
  .map((d) => path.join(d.name, 'migration.sql'))
  .filter((f) => fs.existsSync(path.join(dir, f)))
  .filter((f) => dropsHnsw.test(fs.readFileSync(path.join(dir, f), 'utf8')));

if (offenders.length) {
  console.error('These migrations drop an HNSW index (generated by Prisma, not intended):');
  offenders.forEach((f) => console.error(`  - prisma/migrations/${f}`));
  console.error('Delete the DROP INDEX statements for *_hnsw_idx from them. See README, "Migrations".');
  process.exit(1);
}
console.log('Migration check passed: no HNSW index drops.');
